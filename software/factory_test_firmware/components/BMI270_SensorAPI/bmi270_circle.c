/*!
 * @brief This internal API gets circle gesture configurations
 */
static int8_t get_circle_gesture_detection_config(struct bmi2_circle_gest_det_config *config, struct bmi2_dev *dev)
{
    /* Variable to define error */
    int8_t rslt;

    /* Array to define the feature configuration */
    uint8_t feat_config[BMI2_FEAT_SIZE_IN_BYTES] = { 0 };

    /* Variable to define the array offset */
    uint8_t idx = 0;

    /* Variable to define LSB */
    uint16_t lsb = 0;

    /* Variable to define MSB */
    uint16_t msb = 0;

    /* Variable to define a word */
    uint16_t lsb_msb = 0;

    /* Variable to set flag */
    uint8_t feat_found;

    /* Initialize feature configuration for circle gesture detector */
    struct bmi2_feature_config circle_ges_cfg = { 0, 0, 0 };

    /* Search for circle gesture detector feature and extract its configuration details */
    feat_found = bmi2_extract_input_feat_config(&circle_ges_cfg, BMI2_CIRCLE_GESTURE_DETECTION, dev);
    if (feat_found)
    {
        /* Get the configuration from the page where circle gesture detector feature resides */
        rslt = bmi2_get_feat_config(circle_ges_cfg.page, feat_config, dev);
        if (rslt == BMI2_OK)
        {
            /* Define the offset for feature enable for circle gesture detection */
            idx = circle_ges_cfg.start_addr;

            idx = idx + 2;

            /* Get word to calculate circle detector configuration for setting1 */
            lsb = (uint16_t) feat_config[idx++];
            msb = ((uint16_t) feat_config[idx++] << 8);
            lsb_msb = lsb | msb;

            config->cgd_cfg1.axis_of_rotation = (lsb_msb & BMI270_CIRCLE_GEST_DET_AXIS_SEL_MASK) >>
                                                BMI270_CIRCLE_GEST_DET_AXIS_SEL_POS;

            config->cgd_cfg1.threshold = (lsb_msb & BMI270_CIRCLE_GEST_DET_THRES_MASK) >>
                                         BMI270_CIRCLE_GEST_DET_THRES_POS;

            /* Get word to calculate circle detector configuration for setting2 */
            lsb = (uint16_t) feat_config[idx++];
            msb = ((uint16_t) feat_config[idx++] << 8);
            lsb_msb = lsb | msb;

            /* Get x-select */
            config->cgd_cfg2.threshold_detection = (lsb_msb & BMI270_CIRCLE_GEST_DET_THRES_DET_MASK) >>
                                                   BMI270_CIRCLE_GEST_DET_THRES_DET_POS;

            config->cgd_cfg2.wait_for_timeout = (lsb_msb & BMI270_CIRCLE_GEST_DET_WAIT_TIMEOUT_MASK) >>
                                                BMI270_CIRCLE_GEST_DET_WAIT_TIMEOUT_POS;

            /* Get word to calculate circle detector configuration for setting2 */
            lsb = (uint16_t) feat_config[idx++];
            msb = ((uint16_t) feat_config[idx++] << 8);
            lsb_msb = lsb | msb;

            /* Get x-select */
            config->cgd_cfg3.minimum_gesture_duration = (lsb_msb & BMI270_CIRCLE_GEST_DET_MIN_GEST_DET_MASK) >>
                                                        BMI270_CIRCLE_GEST_DET_MIN_GEST_DET_POS;

            config->cgd_cfg3.maximum_gesture_duration = (lsb_msb & BMI270_CIRCLE_GEST_DET_MAX_GEST_DET_MASK) >>
                                                        BMI270_CIRCLE_GEST_DET_MAX_GEST_DET_POS;

            config->cgd_cfg3.quiet_time_after_circle = (lsb_msb & BMI270_CIRCLE_GEST_DET_QUITE_TIME_MASK) >>
                                                       BMI270_CIRCLE_GEST_DET_QUITE_TIME_POS;
        }
    }
    else
    {
        rslt = BMI2_E_INVALID_SENSOR;
    }

    return rslt;
}

