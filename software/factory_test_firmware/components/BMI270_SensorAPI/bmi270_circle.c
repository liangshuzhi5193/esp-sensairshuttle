/*!
 * @brief This internal API is used to enable or disable main sensors like accel, gyro, aux, and temperature.
 */
static int8_t set_main_sensors(uint64_t sensor_sel, uint8_t enable, struct bmi2_dev *dev)
{
    /* Variable to define error */
    int8_t rslt;

    /* Variable to store register values */
    uint8_t reg_data;

    rslt = bmi2_get_regs(BMI2_PWR_CTRL_ADDR, &reg_data, 1, dev);

    if (rslt == BMI2_OK)
    {
        /* Toggle accelerometer */
        if (sensor_sel & BMI2_ACCEL_SENS_SEL)
        {
            reg_data = enable ? BMI2_SET_BITS(reg_data, BMI2_ACC_EN, BMI2_ENABLE) : BMI2_SET_BIT_VAL0(reg_data,
                                                                                                      BMI2_ACC_EN);
        }

        /* Toggle gyroscope */
        if (sensor_sel & BMI2_GYRO_SENS_SEL)
        {
            reg_data = enable ? BMI2_SET_BITS(reg_data, BMI2_GYR_EN, BMI2_ENABLE) : BMI2_SET_BIT_VAL0(reg_data,
                                                                                                      BMI2_GYR_EN);
        }

        /* Toggle auxiliary sensor */
        if (sensor_sel & BMI2_AUX_SENS_SEL)
        {
            reg_data = enable ? BMI2_SET_BIT_POS0(reg_data, BMI2_AUX_EN, BMI2_ENABLE) : BMI2_SET_BIT_VAL0(reg_data,
                                                                                                          BMI2_AUX_EN);
        }

        /* Toggle temperature sensor */
        if (sensor_sel & BMI2_TEMP_SENS_SEL)
        {
            reg_data = enable ? BMI2_SET_BITS(reg_data, BMI2_TEMP_EN, BMI2_ENABLE) : BMI2_SET_BIT_VAL0(reg_data,
                                                                                                       BMI2_TEMP_EN);
        }

        /* Apply changes to the power control register */
        if (sensor_sel & BMI2_MAIN_SENSORS)
        {
            rslt = bmi2_set_regs(BMI2_PWR_CTRL_ADDR, &reg_data, 1, dev);
        }
    }

    return rslt;
}

/*!
 * @brief This internal API is used to enable main sensors like accel, gyro, aux, and temperature.
 */
static int8_t enable_main_sensors(uint64_t sensor_sel, struct bmi2_dev *dev)
{
    return set_main_sensors(sensor_sel, BMI2_ENABLE, dev);
}

/*!
 * @brief This internal API is used to disable main sensors like accel, gyro, aux, and temperature.
 */
static int8_t disable_main_sensors(uint64_t sensor_sel, struct bmi2_dev *dev)
{
    return set_main_sensors(sensor_sel, BMI2_DISABLE, dev);
}

/*!
 * @brief This internal API is used to enable or disable sensor features.
 */
static int8_t set_sensor_features(uint64_t sensor_sel, uint8_t enable, struct bmi2_dev *dev)
{
    /* Variable to define error */
    int8_t rslt = BMI2_OK;

    /* Toggle any motion feature */
    if (sensor_sel & BMI2_ANY_MOT_SEL)
    {
        rslt = set_any_motion(enable, dev);
    }

    /* Toggle no motion feature */
    if (sensor_sel & BMI2_NO_MOT_SEL)
    {
        rslt = set_no_motion(enable, dev);
    }

    /* Toggle gyroscope user gain */
    if (sensor_sel & BMI2_GYRO_GAIN_UPDATE_SEL)
    {
        rslt = set_gyro_user_gain(enable, dev);
    }

    /* Toggle single tap feature */
    if (sensor_sel & BMI2_SINGLE_TAP_SEL)
    {
        rslt = set_single_tap(enable, dev);
    }

    /* Toggle double tap feature */
    if (sensor_sel & BMI2_DOUBLE_TAP_SEL)
    {
        rslt = set_double_tap(enable, dev);
    }

    /* Toggle triple tap feature */
    if (sensor_sel & BMI2_TRIPLE_TAP_SEL)
    {
        rslt = set_triple_tap(enable, dev);
    }

    /* Toggle circle gesture detection  feature */
    if (sensor_sel & BMI2_CIRCLE_GESTURE_DETECTION_SEL)
    {
        rslt = set_circle_gesture_detection(enable, dev);
    }

    /* Toggle generic interrupt feature */
    if (sensor_sel & BMI2_GENERIC_INTERRUPT_SEL)
    {
        rslt = set_generic_int(enable, dev);
    }

    return rslt;
}

