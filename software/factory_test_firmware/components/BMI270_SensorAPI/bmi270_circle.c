/* @brief This internal API sets tap configurations like sensitivity,
 * single, double and triple tap enable and output-configuration.
 */
static int8_t set_tap_detector_config(struct bmi2_multitap_config *config, struct bmi2_dev *dev)
{
    /* Variable to define error */
    int8_t rslt;

    /* Array to define the feature configuration */
    uint8_t feat_config[BMI2_FEAT_SIZE_IN_BYTES] = { 0 };

    /* Variable to define the array index */
    uint8_t idx = 0;

    /* Variable to define count */
    uint8_t index = 0;

    /* Variable to set flag */
    uint8_t feat_found;

    /* Initialize feature configuration for tap feature */
    struct bmi2_feature_config tap_feat_config = { 0, 0, 0 };

    /* Copy the feature configuration address to a local pointer */
    uint16_t *data_p = (uint16_t *) (void *)feat_config;

    /* Extract the tap feature configuration from the input structure */
    feat_found = bmi2_extract_input_feat_config(&tap_feat_config, BMI2_TAP, dev);

    if (feat_found)
    {

        /* Get the current feature configuration from the device */
        rslt = bmi2_get_feat_config(tap_feat_config.page, feat_config, dev);

        if (rslt == BMI2_OK)
        {

            /* Set the index to the start address of the tap feature */
            idx = tap_feat_config.start_addr;

            /* Get offset in words since all the features are set in words length */
            idx = idx / 2;

            /* Set tap Settings 1 */
            *(data_p + idx) = config->settings_1;
            idx++;

            /* Set tap Settings 2 */
            *(data_p + idx) = config->settings_2;
            idx++;

            /* Set tap Settings 3 */
            *(data_p + idx) = config->settings_3;
            idx++;

            /* Get total length in bytes to copy from local pointer to the array */
            idx = (uint8_t)(idx * 2) - tap_feat_config.start_addr;

            /* Copy the bytes to be set back to the array */
            for (index = 0; index < idx; index++)
            {
                feat_config[tap_feat_config.start_addr +
                            index] = *((uint8_t *) data_p + tap_feat_config.start_addr + index);
            }

            /* Set the configuration back to the page */
            rslt = bmi2_set_regs(BMI2_FEATURES_REG_ADDR, feat_config, BMI2_FEAT_SIZE_IN_BYTES, dev);
        }
    }
    else
    {
        /* Return an error if the tap feature is not found */
        rslt = BMI2_E_INVALID_SENSOR;
    }

    return rslt;
}

