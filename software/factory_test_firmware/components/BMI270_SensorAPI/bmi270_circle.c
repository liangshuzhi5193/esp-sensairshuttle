esp_err_t bmi270_circle_sensor_create(const bmi270_circle_i2c_config_t *i2c_conf, bmi270_circle_handle_t *handle_ret)
{
    esp_err_t ret = ESP_OK;

    /* Status of api are returned to this variable. */
    int8_t rslt;

    /* Sensor initialization configuration. */
    struct bmi2_dev *bmi = (struct bmi2_dev *) calloc(1, sizeof(struct bmi2_dev));
    ESP_RETURN_ON_FALSE(bmi, ESP_ERR_NO_MEM, TAG, "memory allocation for device handler failed");

    rslt = bmi2_interface_init(bmi, BMI2_I2C_INTF, i2c_conf->i2c_addr, i2c_conf->i2c_handle);
    bmi2_error_codes_print_result(rslt);
    ESP_GOTO_ON_FALSE((BMI2_OK == rslt), ESP_ERR_INVALID_STATE, err, TAG, "bmi2_interface_init failed");

    /* Initialize bmi270. */
    rslt = bmi270_circle_init(bmi);
    bmi2_error_codes_print_result(rslt);
    ESP_GOTO_ON_FALSE((BMI2_OK == rslt), ESP_ERR_INVALID_STATE, err, TAG, "bmi270_circle_init failed");

    ESP_LOGI(TAG, " Create %-15s", (BMI270_CIRCLE_CHIP_ID == 0x24) ? "BMI270" : "BMI220");

    *handle_ret = bmi;
    return ret;

err:
    bmi270_circle_sensor_del(bmi);
    return ret;
}

esp_err_t bmi270_circle_sensor_del(bmi270_circle_handle_t handle)
{
    ESP_RETURN_ON_FALSE(handle, ESP_ERR_INVALID_ARG, TAG, "invalid device handle pointer");
    bmi2_coines_deinit();

    free(handle);

    return ESP_OK;
}
