/*!
 * @brief This internal API sets feature configuration to the sensor.
 */
static int8_t set_feat_config(struct bmi2_sens_config *sens_cfg, uint8_t loop, struct bmi2_dev *dev)
{
    /* Variable to define error */
    int8_t rslt;

    switch (sens_cfg[loop].type)
    {
        /* Set any-motion configuration */
        case BMI2_ANY_MOTION:
            rslt = set_any_motion_config(&sens_cfg[loop].cfg.any_motion, dev);
            break;

        /* Set no-motion configuration */
        case BMI2_NO_MOTION:
            rslt = set_no_motion_config(&sens_cfg[loop].cfg.no_motion, dev);
            break;

        /* Set tap configuration */
        case BMI2_TAP:
            rslt = set_tap_detector_config(&sens_cfg[loop].cfg.multi_tap_cfg, dev);
            break;

        /* Set circle gesture detection configuration*/
        case BMI2_CIRCLE_GESTURE_DETECTION:
            rslt = set_circle_gesture_detection_config(&sens_cfg[loop].cfg.circle_gest_det, dev);
            break;

        /* Set generic interrupt configuration*/
        case BMI2_GENERIC_INTERRUPT:
            rslt = set_generic_int_config(&sens_cfg[loop].cfg.gen_int, dev);
            break;

        default:
            rslt = BMI2_E_INVALID_SENSOR;
            break;
    }

    return rslt;
}

